CREATE TABLE IF NOT EXISTS plan_generations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    request_id VARCHAR(36) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL, attempt INTEGER NOT NULL DEFAULT 1,
    quota_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    plan_id BIGINT,
    CONSTRAINT uk_generation_user_request UNIQUE (user_id, request_id)
);
CREATE INDEX IF NOT EXISTS ix_generation_user_status ON plan_generations(user_id, status, expires_at);
CREATE TABLE IF NOT EXISTS plan_usage_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    quota_date DATE NOT NULL,
    used INTEGER NOT NULL,
    CONSTRAINT uk_usage_user_date UNIQUE (user_id, quota_date)
);
CREATE TABLE IF NOT EXISTS auth_grants (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    family_id VARCHAR(36) NOT NULL,
    kind VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_auth_grant_family ON auth_grants(family_id);
CREATE INDEX IF NOT EXISTS ix_auth_grant_expiry ON auth_grants(expires_at);
